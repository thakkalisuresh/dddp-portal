#!/usr/bin/env node
/**
 * Generates docs/ERROR_CODES.md from the registry.
 * test/error-codes.test.js re-runs this and fails on drift, so the docs cannot rot.
 */

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { ERROR_CODES, DOMAINS, domainOf } from '../functions/lib/error-codes.js';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'docs', 'ERROR_CODES.md');

const SEV_LABEL = { fatal: '**fatal**', error: 'error', warn: 'warn' };

export function render() {
  const lines = [
    '# Error codes',
    '',
    '<!-- GENERATED by scripts/gen-error-docs.mjs — do not edit by hand. -->',
    '<!-- Run `npm run errdoc` after changing functions/lib/error-codes.js. -->',
    '',
    'Routing: `fatal` and `error` push to Telegram immediately, `warn` batches into the',
    'daily digest, and everything lands in the `error_log` table visible under god mode.',
    '',
    'Ask the bot a code and it will explain it.',
    '',
  ];

  for (const domain of DOMAINS) {
    const codes = Object.keys(ERROR_CODES).filter((c) => domainOf(c) === domain);
    if (!codes.length) continue;
    lines.push(`## ${domain}`, '', '| Code | Severity | Status | Meaning |', '|---|---|---|---|');
    for (const code of codes) {
      const { severity, message, planned } = ERROR_CODES[code];
      const status = planned ? 'planned' : 'live';
      lines.push(`| \`${code}\` | ${SEV_LABEL[severity]} | ${status} | ${message} |`);
    }
    lines.push('');
  }

  const all = Object.values(ERROR_CODES);
  const planned = all.filter((e) => e.planned).length;
  const fatal = all.filter((e) => e.severity === 'fatal').length;
  lines.push(
    '---',
    '',
    `${all.length} codes across ${DOMAINS.length} domains — ${fatal} fatal, ${planned} awaiting their call site.`,
    '',
    '`planned` codes are reserved for phases not yet built. A test asserts that a code',
    'gaining a call site must drop the flag, so `planned` cannot become a permanent excuse.',
    ''
  );

  return lines.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(out, render());
  console.log(`wrote ${out}`);
}
