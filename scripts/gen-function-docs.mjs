#!/usr/bin/env node
/**
 * Generates docs/FUNCTIONS.md from the source.
 *
 * A hand-written function reference for a codebase this size is stale within a
 * week and then actively misleading — it tells you a function exists that was
 * renamed, or omits the one you needed. This reads the exports and the first
 * line of each doc comment, and test/function-docs.test.js re-runs it and
 * fails on drift, exactly as docs/ERROR_CODES.md already works.
 *
 *   npm run fndoc
 *
 * The one-line summary comes from the doc comment above the export. A function
 * with no comment is listed with a blank, which is deliberate: the gap in the
 * generated file is the nudge to write one.
 */

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const out = join(root, 'docs', 'FUNCTIONS.md');

/** Where the code lives, and what each area is for. */
const AREAS = [
  { dir: 'functions/lib', title: 'Server — lib',
    blurb: 'Pure logic and I/O helpers. Everything testable lives here rather than in the router.' },
  { dir: 'functions', title: 'Server — router', only: ['index.js'],
    blurb: 'One router. Route table at the top, handlers below it.' },
  { dir: 'public/js', title: 'Browser',
    blurb: 'No framework and no build step. Modules are loaded directly, and the CSP forbids inline script.' },
  { dir: 'scripts', title: 'Scripts',
    blurb: 'Run by hand. Several touch production and say so.' },
];

const files = (dir, only) => readdirSync(join(root, dir))
  .filter((f) => f.endsWith('.js') || f.endsWith('.mjs'))
  .filter((f) => !only || only.includes(f))
  .sort();

/**
 * The first sentence of the doc comment immediately above a line.
 *
 * Deliberately only the first sentence: the reference is an index, and anyone
 * who needs the reasoning should be reading the code, where all of it lives.
 */
function summaryAbove(lines, index) {
  let i = index - 1;
  while (i >= 0 && lines[i].trim() === '') i -= 1;
  if (i < 0 || !lines[i].trim().startsWith('*/')) return '';

  const body = [];
  i -= 1;
  while (i >= 0 && !lines[i].trim().startsWith('/**')) {
    body.unshift(lines[i].replace(/^\s*\*ā?\s?/, '').replace(/^\s*\*\s?/, '').trim());
    i -= 1;
  }
  if (i < 0) return '';

  const text = body.join(' ').replace(/\s+/g, ' ').trim();
  if (!text) return '';
  const stop = text.search(/\.(\s|$)/);
  return (stop === -1 ? text : text.slice(0, stop + 1)).trim();
}

const EXPORT_RE =
  /^export\s+(?:async\s+)?function\s+(\w+)|^export\s+(?:const|class)\s+(\w+)/;

function scan(path) {
  const lines = readFileSync(join(root, path), 'utf8').split('\n');
  const items = [];
  lines.forEach((line, i) => {
    const m = EXPORT_RE.exec(line);
    if (!m) return;
    const name = m[1] ?? m[2];
    const kind = /function/.test(line) ? 'fn'
      : /class/.test(line) ? 'class'
      : /=\s*(\(|async|function)/.test(line) ? 'fn' : 'const';
    items.push({ name, kind, line: i + 1, summary: summaryAbove(lines, i) });
  });
  return items;
}

/** The module's own purpose: the first sentence of its top-of-file comment. */
function moduleSummary(path) {
  const lines = readFileSync(join(root, path), 'utf8').split('\n');
  if (!lines[0]?.trim().startsWith('/**')) return '';
  const body = [];
  for (let i = 1; i < lines.length && !lines[i].trim().startsWith('*/'); i += 1) {
    body.push(lines[i].replace(/^\s*\*\s?/, '').trim());
  }
  const text = body.join(' ').replace(/\s+/g, ' ').trim();
  const stop = text.search(/\.(\s|$)/);
  return (stop === -1 ? text : text.slice(0, stop + 1)).trim();
}

export function render() {
  const lines = [
    '# Functions',
    '',
    '<!-- GENERATED by scripts/gen-function-docs.mjs — do not edit by hand. -->',
    '<!-- Run `npm run fndoc`. test/function-docs.test.js fails if this drifts. -->',
    '',
    'Every export, with the first line of its doc comment. An index, not an',
    'explanation — the reasoning lives in the code, which is where it stays true.',
    '',
    'A blank summary means the export has no doc comment. That gap is the point:',
    'it is easier to notice here than in the file.',
    '',
  ];

  let total = 0;
  let undocumented = 0;

  for (const area of AREAS) {
    lines.push(`## ${area.title}`, '', area.blurb, '');
    for (const file of files(area.dir, area.only)) {
      const path = join(area.dir, file);
      const items = scan(path);
      if (!items.length) continue;

      const purpose = moduleSummary(path);
      lines.push(`### \`${relative(root, join(root, path))}\``, '');
      if (purpose) lines.push(purpose, '');
      lines.push('| | Export | What it does |', '|---|---|---|');
      for (const it of items) {
        total += 1;
        if (!it.summary) undocumented += 1;
        lines.push(`| ${it.kind} | \`${it.name}\` | ${it.summary} |`);
      }
      lines.push('');
    }
  }

  lines.push('---', '',
    `${total} exports. ${undocumented} have no doc comment.`, '');
  return lines.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(out, render());
  console.log(`wrote ${out}`);
}
